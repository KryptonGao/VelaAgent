/** Plan 模式下只放行查阅命令。管道和连接符拆开后，每一段都要在允许名单里。 */
export function isPlanSafeCommand(command: string): boolean {
  const parts = command
    .replace(/\|\|/g, "\n")
    .replace(/&&/g, "\n")
    .split(/[;\n|]/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
  if (parts.length === 0) return false;
  return parts.every((part) => isSingleSafe(part));
}

function isSingleSafe(command: string): boolean {
  if (destructivePatterns.some((pattern) => pattern.test(command))) return false;
  return safePatterns.some((pattern) => pattern.test(command));
}
